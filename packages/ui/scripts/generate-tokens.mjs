// Generates src/theme/tokens.ts from design/tokens.json (the Padel Pink design system).
// Run: node packages/ui/scripts/generate-tokens.mjs
// Re-run after replacing design/tokens.json with a newer export of the design system.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = JSON.parse(readFileSync(join(root, 'design/tokens.json'), 'utf8'));

/** "pink-500" -> "pink500", "ink-soft" -> "inkSoft", "radius-lg" (prefix removed) -> "lg". */
const camel = (name) => name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const px = (value) => {
  const match = /^(-?\d+(?:\.\d+)?)px$/.exec(String(value));
  if (!match) throw new Error(`Expected a px value, got "${value}"`);
  return Number(match[1]);
};
const round = (n) => Math.round(n * 100) / 100;
/** Serialises a value as single-line TypeScript with single quotes and unquoted keys. */
const ser = (v) => {
  if (typeof v === 'string') return `'${v}'`;
  if (typeof v === 'number') return String(v);
  return `{ ${Object.entries(v)
    .map(([k, x]) => `${/^[a-zA-Z_]\w*$/.test(k) ? k : `'${k}'`}: ${ser(x)}`)
    .join(', ')} }`;
};

// Colours: first theme only (light).
const theme = source.color.themes[0].id;
const colors = source.color.tokens.map((t) => [camel(t.name), t.value[theme], t.usage]);

// Spacing: "space-4" -> space4.
const spacing = source.spacing.tokens.map((t) => [camel(t.name), px(t.value), t.usage]);

// Radius: "radius-lg" -> lg, pill stays 999.
const radius = source.radius.tokens.map((t) => [camel(t.name.replace(/^radius-/, '')), px(t.value), t.usage]);

// Type: Outfit, one family per weight. Weight is never emitted as fontWeight.
const families = {
  400: 'Outfit_400Regular',
  500: 'Outfit_500Medium',
  600: 'Outfit_600SemiBold',
  700: 'Outfit_700Bold',
  800: 'Outfit_800ExtraBold',
};
const textStyles = source.type.groups.flatMap((g) =>
  g.styles.map((s) => {
    const fontSize = px(s.fontSize);
    const family = families[Number(s.fontWeight)];
    if (!family) throw new Error(`No Outfit family for weight ${s.fontWeight} (${s.name})`);
    const style = { fontFamily: family, fontSize, lineHeight: px(s.lineHeight) };
    if (s.letterSpacing) {
      const em = /^(-?\d+(?:\.\d+)?)em$/.exec(s.letterSpacing);
      if (!em) throw new Error(`Expected em letter spacing, got "${s.letterSpacing}" (${s.name})`);
      style.letterSpacing = round(Number(em[1]) * fontSize);
    }
    return [camel(s.name), style, s.usage];
  }),
);

// Shadows: CSS "0 10px 22px rgba(r,g,b,a)" -> iOS shadow props; shadowRadius is half the blur.
// Elevation (Android) is approximate and set per token from the design-system translation notes.
const elevation = { shadowBrand: 8, shadowFloat: 10, shadowCard: 2 };
const hex = (n) => n.toString(16).padStart(2, '0').toUpperCase();
const shadows = source.shadow.tokens.map((t) => {
  const m = /^0 (-?\d+)px (\d+)px rgba\((\d+),(\d+),(\d+),([\d.]+)\)$/.exec(t.value);
  if (!m) throw new Error(`Cannot parse shadow "${t.value}"`);
  const name = camel(t.name);
  if (!(name in elevation)) throw new Error(`No Android elevation for ${name}`);
  return [
    name,
    {
      shadowColor: `#${hex(+m[3])}${hex(+m[4])}${hex(+m[5])}`,
      shadowOffset: { width: 0, height: Number(m[1]) },
      shadowOpacity: Number(m[6]),
      shadowRadius: round(Number(m[2]) / 2),
      elevation: elevation[name],
    },
    t.usage,
  ];
});

const comment = (usage) => `  /** ${usage.replace(/\*\//g, '* /')} */\n`;
const block = (name, entries, render = ser) =>
  `export const ${name} = {\n${entries.map(([k, v, usage]) => `${comment(usage)}  ${k}: ${render(v)},`).join('\n')}\n} as const;\n`;

const typeBlock = `export const type = {\n${textStyles
  .map(
    ([k, v, usage]) =>
      `${comment(usage)}  ${k}: {\n${Object.entries(v)
        .map(([prop, x]) => `    ${prop}: ${ser(x)},`)
        .join('\n')}\n  },`,
  )
  .join('\n')}\n} as const;\n`;

const shadowBlock = `export const shadows = {\n${shadows
  .map(
    ([k, v, usage]) =>
      `${comment(usage)}  ${k}: {\n${Object.entries(v)
        .map(([prop, x]) => `    ${prop}: ${ser(x)},`)
        .join('\n')}\n  },`,
  )
  .join('\n')}\n} as const;\n`;

const out = `/**
 * GENERATED by scripts/generate-tokens.mjs from design/tokens.json (${source.name}). Do not edit by hand.
 * Units are dp. Hairlines are real 1.5 borders (see \`borderWidth\`), not StyleSheet.hairlineWidth.
 */

${block('colors', colors)}
export type ColorToken = keyof typeof colors;

${block('spacing', spacing)}
${block('radius', radius)}
/** Border width for cards, dividers and control borders. */
export const borderWidth = 1.5;

/** Outfit, one family per weight. Never combine these with fontWeight: Android ignores it for custom fonts. */
export const fontFamily = {
${Object.entries(families)
  .map(([w, f]) => `  ${w}: '${f}',`)
  .join('\n')}
} as const;

${typeBlock}
export type TextStyleToken = keyof typeof type;

/** iOS reads the shadow* props; Android reads elevation (approximate, check on a real device). */
${shadowBlock}`;

writeFileSync(join(root, 'src/theme/tokens.ts'), out);
console.log('Wrote src/theme/tokens.ts');
